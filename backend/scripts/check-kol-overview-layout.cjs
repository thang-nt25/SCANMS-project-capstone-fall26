require('dotenv/config');
const { PrismaClient } = require('@prisma/client');
const { PrismaPg } = require('@prisma/adapter-pg');
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) });
(async () => {
  let browser;
  try {
    const user = await db.user.findFirst({ where: { email: 'kol.bronze@scanms.vn', isActive: true, isDeleted: false }, select: { id: true, role: true, email: true, fullName: true } });
    if (!user) throw Error('Missing test collaborator');
    const token = require('jsonwebtoken').sign({ sub: user.id, role: user.role, email: user.email }, process.env.JWT_SECRET, { expiresIn: '3m' });
    const p = await import('../../frontend/node_modules/puppeteer-core/lib/puppeteer/puppeteer-core.js');
    browser = await p.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-first-run', '--disable-extensions'] });
    const page = await browser.newPage(); const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.setViewport({ width: 1440, height: 1000 });
    await page.evaluateOnNewDocument(({ user, token }) => {
      localStorage.setItem('token', token); localStorage.setItem('user', JSON.stringify(user));
      localStorage.setItem('scanms-current-role', 'kol'); localStorage.setItem('scanms-active-workspace', 'kol');
    }, { user, token });
    let liveFixture = false;
    await page.setRequestInterception(true);
    page.on('request', request => {
      if (liveFixture && new URL(request.url()).pathname === '/api/dashboard/collaborator/live-sessions-summary') return void request.respond({ status: 200, contentType: 'application/json', body: JSON.stringify({ data: { success: true, totalSessions: 1, totals: { totalLiveRevenue: 1000000, totalLiveCommission: 120000, totalLiveOrders: 2 }, sessions: [{ id: 'fixture-live', title: 'Phiên chăm sóc da', storeName: 'Cửa hàng kiểm thử', startsAt: '2026-11-14T02:00:00Z', status: 'ENDED', metrics: { ordersCount: 2, grossRevenue: 1000000, commissionEarned: 120000 } }] } }) });
      if (new URL(request.url()).pathname.startsWith('/api/') && !['GET', 'OPTIONS'].includes(request.method())) return void request.abort();
      void request.continue();
    });
    await page.goto('http://localhost:5173/collaborator/dashboard', { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.kol-recent-order-row', { timeout: 30000 });
    if ((await page.$$('.kol-recent-order-row')).length > 3 || await page.$('.kol-orders-table')) throw Error('Overview is not compact');
    await page.click('#kol-dashboard-period');
    await page.waitForSelector('[role="option"]');
    await page.evaluate(() => [...document.querySelectorAll('[role="option"]')].find(element => element.textContent.includes('30 ngày')).click());
    await page.waitForFunction(() => document.querySelector('#kol-overview')?.textContent.includes('/30 ngày có phát sinh'));
    const overviewHeight = await page.$eval('#kol-overview', element => element.scrollHeight);
    await page.evaluate(() => [...document.querySelectorAll('button')].find(element => element.textContent.includes('Xem số liệu theo ngày')).click());
    await page.waitForSelector('.kol-daily-dialog');
    if ((await page.$$('.kol-daily-table tbody tr')).length !== 10) throw Error('Expected ten days per page');
    if ((await page.$eval('#kol-overview', element => element.scrollHeight)) > overviewHeight + 2) throw Error('Daily data still expands overview');
    const firstDay = await page.$eval('.kol-daily-table tbody tr th', element => element.textContent);
    const totalPeriod = await page.$eval('.kol-daily-table tfoot', element => element.textContent);
    await page.$eval('.kol-daily-dialog .kol-report-pagination button:last-child', element => element.click());
    if (await page.$eval('.kol-daily-table tbody tr th', element => element.textContent) === firstDay) throw Error('Daily pagination did not change rows');
    if (await page.$eval('.kol-daily-table tfoot', element => element.textContent) !== totalPeriod) throw Error('Period total changed across pages');
    await page.screenshot({ path: '../artifacts/manual-finance/kol-daily-modal.png' });
    await page.keyboard.press('Escape');
    await page.$eval('.kol-recent-orders', element => element.scrollIntoView({ block: 'center' }));
    await page.screenshot({ path: '../artifacts/manual-finance/kol-compact-overview.png' });
    await page.$eval('.kol-recent-orders > header > a', element => element.click());
    await page.waitForSelector('.kol-orders-table tbody tr', { timeout: 30000 });
    if (new URL(page.url()).pathname !== '/collaborator/reports') throw Error('Reports must have a separate route');
    if ((await page.$$('.kol-orders-table tbody tr')).length > 10) throw Error('More than ten orders');
    await page.screenshot({ path: '../artifacts/manual-finance/kol-overview-desktop.png' });
    const firstCode = await page.$eval('.kol-order-link', element => element.textContent);
    await page.$eval('.kol-order-link', element => element.click());
    await page.waitForSelector('[role="dialog"]');
    if (!await page.$eval('[role="dialog"]', (element, code) => element.textContent.includes(code), firstCode)) throw Error('Wrong order detail');
    await page.keyboard.press('Escape');
    const next = '.kol-report-pagination button:last-child';
    if (!await page.$eval(next, element => element.disabled)) {
      await page.$eval(next, element => element.click());
      await page.waitForFunction(code => document.querySelector('.kol-order-link')?.textContent !== code, {}, firstCode);
      if ((await page.$$('.kol-orders-table tbody tr')).length > 10) throw Error('Second page limit');
    }
    const tab = async index => page.$eval(`[aria-label="Loại báo cáo tiếp thị"] > button:nth-child(${index})`, element => element.click());
    await tab(2); await page.waitForSelector('.kol-rate-button');
    await page.$eval('.kol-rate-button', element => element.click()); await page.waitForSelector('[role="dialog"]');
    await page.keyboard.press('Escape');
    await tab(3); await page.waitForSelector('.kol-store-link');
    await page.$eval('.kol-stores-table', element => element.scrollIntoView({ block: 'center' }));
    await page.screenshot({ path: '../artifacts/manual-finance/kol-overview-stores.png' });
    const storeName = await page.$eval('.kol-store-link', element => element.textContent);
    await page.$eval('.kol-store-link', element => element.click());
    await page.waitForSelector('.kol-store-filter');
    await page.waitForFunction(name => [...document.querySelectorAll('.kol-orders-table tbody tr')].every(row => row.textContent.includes(name)), {}, storeName);
    await page.$eval('.kol-store-filter button', element => element.click());
    await tab(4); await page.waitForSelector('.kol-live-metrics');
    await page.$eval('.kol-live-report', element => element.scrollIntoView({ block: 'center' }));
    await page.screenshot({ path: '../artifacts/manual-finance/kol-overview-live.png' });
    await page.setViewport({ width: 390, height: 1000 });
    if (!await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)) throw Error('Mobile page overflow');
    liveFixture = true;
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForSelector('[aria-label="Loại báo cáo tiếp thị"]');
    await tab(4); await page.waitForSelector('.kol-live-table tbody tr');
    if (!await page.$eval('.kol-live-table', element => element.textContent.includes('Phiên chăm sóc da') && element.textContent.includes('120.000'))) throw Error('Live data table failed');
    await page.setViewport({ width: 1440, height: 1000 });
    await page.$eval('.kol-live-report', element => element.scrollIntoView({ block: 'center' }));
    await page.screenshot({ path: '../artifacts/manual-finance/kol-overview-live-fixture.png' });
    if (errors.length) throw Error(errors.join('; '));
    console.log('Verified real KOL overview: ten-order pagination, exact order dialog, rate modal, full store breakdown and store filter, live panel and mobile fit. No API writes.');
  } finally { await browser?.close(); await db.$disconnect(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
