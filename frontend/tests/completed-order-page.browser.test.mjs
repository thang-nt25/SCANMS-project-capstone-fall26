import test from 'node:test';
import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const base = process.env.GHN_UI_TEST_URL;
test('completed product row opens a dedicated order page with saved totals, reviews and correct links', { skip: !base, timeout: 45000 }, async () => {
  const origin = new URL(base).origin;
  assert.ok(['localhost', '127.0.0.1'].includes(new URL(base).hostname));
  const browser = await puppeteer.launch({ executablePath: 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe', headless: true, timeout: 10000, args: ['--no-sandbox'] });
  const user = { id: 'qa-customer', fullName: 'Tuấn Đình', role: 'CUSTOMER' };
  const order = { id: '00000000-0000-4000-8000-000000000001', externalOrderSn: 'DH-2026-QA', status: 'COMPLETED', createdAt: '2026-10-19T03:51:00Z', deliveredAt: '2026-10-20T03:00:00Z', completedAt: '2026-10-20T04:00:00Z', customerName: user.fullName, customerPhone: '0901234567', shippingAddress: 'Khu Công Nghệ Cao, Phường Phước Long B, Thành phố Thủ Đức, Thành phố Hồ Chí Minh', finalAmount: 271001, subtotalAmount: 250000, shippingFee: 21001, discountAmount: 0, rawPayload: { paymentMethod: 'PAYOS', paymentStatus: 'PAID', ghnOrderCode: 'L8RAYL', ghnShippedAt: '2026-10-19T04:00:00Z', ghnEnvironment: 'TEST' }, storeId: 'qa-shop', store: { id: 'qa-shop', name: 'Sora Skin', slug: 'sora-skin' }, orderItems: [{ id: 'qa-item', productId: 'qa-product', quantity: 1, unitPrice: 250000, product: { id: 'qa-product', sku: 'QA-SERUM', title: 'Serum Vitamin C', imageUrl: '/assets/categories/skin-v1.png' }, variant: { name: '30 ml / Tiêu chuẩn' } }], productReviews: [{ id: 'qa-review', productId: 'qa-product', customerName: user.fullName, createdAt: '2026-10-20T04:00:00Z', rating: 5, comment: 'Sản phẩm dùng tốt.', status: 'APPROVED', images: [] }] };
  const writes = [], errors = [];
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 1440, height: 1000 });
    page.setDefaultTimeout(10000);
    page.on('pageerror', error => errors.push(error.message));
    await page.evaluateOnNewDocument(user => { localStorage.setItem('token', 'qa-completed'); localStorage.setItem('user', JSON.stringify(user)); localStorage.setItem('scanms_analytics_consent', 'denied'); }, user);
    await page.setRequestInterception(true);
    page.on('request', req => {
      const url = new URL(req.url());
      if (url.pathname === '/src/services/chat-socket.service.ts') return req.respond({ status: 200, contentType: 'application/javascript', body: 'const s={connected:false,active:false,on(){return this},off(){return this},emit(){},connect(){return this}};export const getChatSocket=()=>s;export const isChatSocketAuthenticated=()=>false;export const disconnectChatSocket=()=>{};' });
      if (url.pathname.startsWith('/api/') || url.port === '3000') {
        const headers = { 'Access-Control-Allow-Origin': origin, 'Access-Control-Allow-Credentials': 'true', 'Access-Control-Allow-Headers': req.headers()['access-control-request-headers'] || '*', 'Access-Control-Allow-Methods': 'GET,POST,OPTIONS' };
        if (req.method() === 'OPTIONS') return req.respond({ status: 204, headers });
        if (req.method() !== 'GET') writes.push(url.pathname);
        let data = [], status = 200;
        if (url.pathname.endsWith('/auth/me')) data = user;
        if (url.pathname.endsWith('/customer/profile')) data = { user, stats: {} };
        if (url.pathname.endsWith('/customer/orders')) data = { orders: [order], total: 1 };
        if (url.pathname.endsWith('/customer/orders/' + order.id)) data = order;
        if (url.pathname.endsWith('/customer/orders/not-owned')) { status = 403; data = { message: 'Forbidden' }; }
        if (url.pathname.includes('/shipping/ghn/track/')) data = { status: 'delivered', statusText: 'Giao hàng thành công', timeline: [{ status: 'picked', title: 'Đã lấy hàng', time: '2026-10-19T05:00:00Z' }, { status: 'delivered', title: 'Đã giao', time: order.deliveredAt }] };
        if (url.pathname.endsWith('/customer/cart')) data = { items: [] };
        if (url.pathname.includes('/notifications/unread')) data = { unreadCount: 0, categoryUnreadCounts: {} };
        if (url.pathname.endsWith('/notifications')) data = { notifications: [], total: 0 };
        return req.respond({ status, headers, contentType: 'application/json', body: JSON.stringify({ success: status === 200, data }) });
      }
      if (url.origin !== origin && !['data:', 'blob:'].includes(url.protocol)) return req.abort();
      return req.continue();
    });
    await page.goto(origin + '/customer/orders', { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('[data-order-detail-link]');
    assert.equal(await page.$('[data-order-code] [data-order-product-link]'), null, 'completed card should open the order instead of public product details');
    await page.click('[data-order-detail-link]');
    await page.waitForSelector('.purchase-detail-progress');
    assert.equal(new URL(page.url()).pathname, '/customer/orders/' + order.id);
    assert.equal(await page.$('.customer-order-detail-dialog'), null);
    const text = await page.$eval('.customer-purchase-detail', el => el.textContent);
    assert.match(text, /Đơn hàng đã hoàn thành/);
    assert.match(text, /271\.001/);
    assert.match(text, /Chuyển khoản qua PayOS/);
    assert.match(text, /Đã thanh toán/);
    await page.waitForFunction(() => document.querySelectorAll('.purchase-detail-progress time').length === 5);
    assert.equal(await page.$eval('.purchase-detail-progress li:nth-child(2) time', el => el.getAttribute('datetime')), '2026-10-19T04:00:00Z');
    assert.equal(await page.$eval('.purchase-detail-progress li:nth-child(3) time', el => el.getAttribute('datetime')), '2026-10-19T05:00:00Z');
    assert.equal(await page.$eval('.purchase-detail-products header a', el => el.getAttribute('href')), '/shop/sora-skin');
    assert.equal(await page.$eval('.purchase-product-image', el => el.getAttribute('href')), '/products/qa-product');
    await page.screenshot({ path: join(tmpdir(), 'scanms-completed-order-desktop.png') });
    await page.click('.purchase-product-review');
    await page.waitForSelector('.order-reviews-dialog[open]');
    assert.match(await page.$eval('.order-reviews-dialog', el => el.textContent), /Sản phẩm dùng tốt/);
    await page.keyboard.press('Escape');
    await page.evaluate(() => document.querySelector('.workspace-page-column').scrollTo({ top: 9999 }));
    await page.screenshot({ path: join(tmpdir(), 'scanms-completed-order-payment.png') });
    await page.setViewport({ width: 390, height: 844 });
    assert.equal(await page.$eval('.customer-purchase-detail', el => el.scrollWidth <= el.clientWidth), true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: join(tmpdir(), 'scanms-completed-order-mobile.png') });
    await page.click('.purchase-detail-top > a');
    await page.waitForSelector('[data-order-detail-link]');
    assert.equal(new URL(page.url()).pathname, '/customer/orders');
    await page.click('[data-order-detail-link]');
    await page.waitForSelector('.purchase-detail-progress');
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.purchase-detail-progress');
    await page.click('.purchase-primary');
    await page.waitForFunction(() => location.pathname === '/products/QA-SERUM');
    order.status = 'PENDING';
    order.productReviews = [];
    order.rawPayload = { paymentMethod: 'WALLET', paymentStatus: 'PAID' };
    order.completedAt = null;
    order.deliveredAt = null;
    await page.setViewport({ width: 1440, height: 1000 });
    await page.goto(origin + '/customer/orders', { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.customer-order-card');
    await page.evaluate(() => [...document.querySelectorAll('.customer-order-card button')].find(el => el.textContent.trim() === 'Xem chi tiết').click());
    await page.waitForSelector('.purchase-detail-progress');
    assert.equal(new URL(page.url()).pathname, '/customer/orders/' + order.id);
    assert.equal(await page.$$eval('.purchase-detail-progress .is-reached', els => els.length), 1);
    assert.equal(await page.$$eval('.purchase-detail-progress time', els => els.length), 1);
    assert.match(await page.$eval('.purchase-detail-status', el => el.textContent), /Chờ Shop xác nhận/);
    assert.equal(await page.$('.purchase-primary'), null);
    await page.click('.purchase-cancel-action');
    await page.waitForSelector('.customer-cancel-dialog');
    assert.equal(writes.length, 0, 'opening cancellation must not cancel without confirmation');
    await page.keyboard.press('Escape');
    await page.waitForSelector('.customer-cancel-dialog', { hidden: true });
    await page.screenshot({ path: join(tmpdir(), 'scanms-pending-order-detail.png') });
    await page.click('.purchase-detail-top a');
    await page.waitForSelector('.customer-order-card');
    assert.equal(await page.$eval('[aria-label="Tìm đơn mua"]', el => el.value), '');
    assert.equal(new URL(page.url()).search, '');
    await page.goto(origin + '/customer/orders/not-owned', { waitUntil: 'domcontentloaded' });
    await page.waitForSelector('.purchase-load-state [role="alert"]');
    assert.equal(await page.$('.purchase-detail-progress'), null);
    assert.equal(writes.length, 0, 'viewing and buying again must not place an order or send a chat');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
